def get_text(key, lang=None):
    """Joriy (yoki berilgan) tilda matnni qaytaradi. Topilmasa, o'zbekchaga tushadi."""
    lang = (lang or translation.get_language() or DEFAULT_LANG).split('-')[0]
    return TEXTS.get(lang, TEXTS[DEFAULT_LANG]).get(key) or TEXTS[DEFAULT_LANG][key]